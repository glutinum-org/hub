let pageSource (binding: Binding) =
    $"""module {binding.Name}.Tests.Page

open Fable.Core
open Glutinum

open type Glutinum.Web.Exports

type {binding.ModuleName} = {binding.ModuleName}.Exports

// The page exercises the binding in a real browser, the tests read the results in the DOM
let private report (id: string) (text: string) =
    let element = document.createElement "p"
    element.id <- id
    element.textContent <- text
    document.body.appendChild element |> ignore

// Replace with calls to {binding.ModuleName}
report "loaded" "ok"
"""

