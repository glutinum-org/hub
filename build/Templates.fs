/// `>= 4.4.0 < 5.0.0`, the range Femto installs for a pinned version
let private npmRange (version: string) =
    match version.Split('.') with
    | [| major; _; _ |] -> $"&gt;= {version} &lt; {int major + 1}.0.0"
    | _ -> version

let project
    (binding: Binding)
    (npm: (string * string) option)
    (packages: string list)
    (externals: Binding list)
    (hasExtensions: bool)
    =
    let extensions =
        let compile = $"<Compile Include=\"{binding.Name}.Extensions.fs\" />"

        if hasExtensions then
            $"\n        {compile}"
        else
            $"\n        <!-- {compile} -->"

    let npmDependencies =
        match npm with
        | None -> ""
        | Some(name, version) ->
            $"\n        <NpmDependencies>\n            <NpmPackage Name=\"{name}\" Version=\"{npmRange version}\" />\n        </NpmDependencies>"

    let references =
        packages
        |> List.map (fun name -> $"        <PackageReference Include=\"{name}\" />\n")
        |> String.concat ""

    let projectReferences =
        match externals with
        | [] -> ""
        | externals ->
            let items =
                externals
                |> List.map (fun external ->
                    $"        <ProjectReference Include=\"../{external.Name}/{external.Name}.fsproj\" />"
                )
                |> String.concat "\n"

            $"    <ItemGroup>\n{items}\n    </ItemGroup>\n"

    $"""<?xml version="1.0" encoding="utf-8"?>
<!-- Written by `./build.sh generate`, the settings are in binding.json -->
<Project Sdk="Microsoft.NET.Sdk">
    <PropertyGroup>
        <TargetFramework>netstandard2.1</TargetFramework>
        <PackageId>{binding.Name}</PackageId>
        <Description>{binding.Config.Description}</Description>
        <PackageReadmeFile>README.md</PackageReadmeFile>
        <FablePackageType>binding</FablePackageType>
        <PackageTags>fable-javascript;fable-binding</PackageTags>
        <ChangelogFile>CHANGELOG.md</ChangelogFile>
        <NoWarn>$(NoWarn);FS0044</NoWarn>{npmDependencies}
    </PropertyGroup>
    <ItemGroup>
        <None Include="README.md" Pack="true" PackagePath="\" />
        <Compile Include="{binding.Name}.fs" />{extensions}
    </ItemGroup>
    <ItemGroup>
        <PackageReference Include="EasyBuild.PackageReleaseNotes.Tasks" />
        <PackageReference Include="Fable.Core" />
        <PackageReference Include="Fable.Package.SDK" />
{references}    </ItemGroup>
{projectReferences}</Project>
"""

let readme (binding: Binding) =
    let package = binding.Config.Package

    $"""# {binding.Name}

{binding.Config.Description}

Generated by [Glutinum](https://github.com/glutinum-org/cli) from [`{package}`](https://www.npmjs.com/package/{package}).

The bindings live in the `Glutinum.{binding.ModuleName}` module, the exports of the package are static members of `Glutinum.{binding.ModuleName}.Exports`.

```fsharp
open Glutinum

type {binding.ModuleName} = {binding.ModuleName}.Exports
```

Install the npm package next to the NuGet package, or run `femto` to do it.

The file `{binding.Name}.fs` is generated by `./build.sh generate {binding.ModuleName}` in the [hub](https://github.com/glutinum-org/hub), do not edit it.
"""

