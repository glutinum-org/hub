module Hub.Commands.New

open System.ComponentModel
open System.IO
open BlackFox.CommandLine
open Spectre.Console.Cli
open Hub
open Hub.Binding
open Hub.Utils

type NewSettings() =
    inherit CommandSettings()

    [<CommandArgument(0, "<package>")>]
    [<Description("The npm package to generate, `@types/leaflet` or `date-fns`")>]
    member val Package: string = "" with get, set

    [<CommandOption("--name <name>")>]
    [<Description("The binding name, `Glutinum.` followed by the module Glutinum derives from the package name otherwise")>]
    member val Name: string = null with get, set

    [<CommandOption("--version <version>")>]
    [<Description("The version of the package to pin, the latest otherwise")>]
    member val Version: string = null with get, set

    [<CommandOption("--description <description>")>]
    member val Description: string = null with get, set

    [<CommandOption("--input <input>")>]
    [<Description("A subpath generated with the package, `date-fns/locale`. Can be repeated")>]
    member val Inputs: string array = [||] with get, set

    [<CommandOption("--external <binding>")>]
    [<Description("A binding of the hub the package depends on, referenced instead of generated. Can be repeated")>]
    member val Externals: string array = [||] with get, set

    [<CommandOption("--tests <kind>")>]
    [<Description("Scaffold tests too: `node` or `browser`")>]
    member val Tests: string = null with get, set

let private latestVersion (package: string) =
    Shell.read
        "npm"
        (CmdLine.empty
         |> CmdLine.appendRaw "view"
         |> CmdLine.appendRaw package
         |> CmdLine.appendRaw "version")
        Workspace.root

type NewCommand() =
    inherit Command<NewSettings>()

    override _.Execute(_, settings) =
        let package = settings.Package

        let name =
            match settings.Name with
            | null
            | "" -> "Glutinum." + moduleNameForPackage (runtimeName package)
            | name -> name

        let dir = Path.Combine(Workspace.bindingsDir, name)

        if Directory.Exists dir then
            failwithf "%s already exists" (Workspace.relative dir)

        let version =
            match settings.Version with
            | null
            | "" -> latestVersion package
            | version -> version

        let externals =
            settings.Externals |> Array.toList |> List.map (fun name -> (find name).Name)

        let binding =
            {
                Name = name
                Dir = dir
                Config =
                    {
                        Package = package
                        Description =
                            match settings.Description with
                            | null
                            | "" ->
                                $"Fable bindings for {runtimeName package}, generated by Glutinum"
                            | description -> description
                        Inputs = package :: Array.toList settings.Inputs
                        Externals = externals
                        Tests = None
                    }
            }

        Directory.CreateDirectory dir |> ignore
        save binding
        File.WriteAllText(binding.PackageJson, Templates.packageJson binding version)
        File.WriteAllText(binding.Changelog, Templates.changelog binding)
        File.WriteAllText(Path.Combine(dir, "README.md"), Templates.readme binding)

        Generate.generateAll [ binding ]

        match settings.Tests with
        | null
        | "" -> ()
        | tests -> AddTests.scaffold binding (Tests.Parse tests)

        printfn $"{name} written in {Workspace.relative dir}, open that folder to work on it"
        0
